def add(a,b):
    return a+b
def substract(a,b):
    return a-b
def multiply(a,b):
    return a*b
def divide(a,b):
    a/b
calc={}
calc['+']=add
calc['-']=substract
calc['*']=multiply
calc['/']=divide
print(logo)
i=True
while i:
    n1 = float(input("Enter the first number: \n"))
    n2 = float(input("Enter the second number: \n"))
    for symbol in calc:
        print(symbol)
    op = input("Pick an operation")
    ans = calc[op](n1, n2)
    print(f"{n1} {op} {n2} = {ans}\n")
    i = input("You want to continue ? (y/n)")
    if i=='n':
        exit()
